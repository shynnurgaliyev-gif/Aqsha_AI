/** Returns true if the message is a help request. */
export function matchHelpCommand(text: string): boolean {
  const t = text.trim().toLowerCase().replace(/[.!?,;]+$/, '');
  return (
    t === 'помощь' ||
    t === 'помоги' ||
    t === '/help' ||
    t === 'help' ||
    t === 'команды' ||
    t === '/команды' ||
    t === 'что умеешь' ||
    t === 'что ты умеешь'
  );
}
