-- =========================================================
-- CATEGORY ALIASES
-- Synonym layer between parser and AI fallback.
-- Pipeline: exact category match → alias match → AI fallback
-- =========================================================

create table if not exists public.category_aliases (
  id             uuid        primary key default gen_random_uuid(),
  category_id    uuid        not null references public.categories(id) on delete cascade,
  alias          text        not null,
  normalized_alias text      not null,
  is_system      boolean     not null default true,
  created_at     timestamptz not null default now(),
  unique(category_id, normalized_alias)
);

create index if not exists idx_category_aliases_norm
  on public.category_aliases(normalized_alias);

create index if not exists idx_category_aliases_category_id
  on public.category_aliases(category_id);

